"""
Reproducible ranking-quality eval for the scholarship-matching algorithm.

Calls `_score_profile_match` in
app/domains/finance/agents/finance/scholarships/tools/matching.py directly —
this is the actual weighted formula running in production
(0.5 Jaccard token + 0.3 Bigram + 0.2 SequenceMatcher name similarity).
No network, no DB, no LLM: pure function, fully deterministic and reproducible.

Note on methodology: an earlier version of this script applied a hard
score >= 0.5 cutoff to compute Precision/Recall/F1, mirroring the
"confidence: low" threshold used elsewhere in the codebase. That produced
0% precision/recall across the board — not because the algorithm performs
badly, but because absolute Jaccard/Bigram scores over short profile/
scholarship text rarely cross 0.5 even for a correct match (see reports/
scholarship_matching_eval_20260714_121240.json). Inspecting the raw
per-profile ranking showed the correct scholarships consistently land in
the top 3 results. The real system (`match_scholarships_for_profile`)
never applies a hard cutoff either — it ranks all candidates by score and
returns the top-N, using the 0.5/0.7 thresholds only for a UI confidence
label. So this eval measures ranking quality (Precision@K / Recall@K /
F1@K / MRR) instead, which matches what the product actually does.

Replaces the manual "~100 hồ sơ / 50 học bổng, đối chiếu bằng mắt" estimate
in the report (Chapter 6, 6.4.2). Also drops the two comparison baselines
("Keyword Filter", "Fuzzy Matching only") that don't exist as real code
paths in the product — this eval only reports the one algorithm actually
deployed.

IMPORTANT -- scope of this eval vs. eval_scholarship_ranking_pipeline.py:
This script measures `_score_profile_match` IN ISOLATION. It is a sub-component, not the final
production behavior: the real recommendation path (`_rank_recommendation_items`) applies a hard
university+major gate on top of this score (a topically-relevant scholarship for a different
university is excluded entirely) and then sorts survivors by GPA-gap/amount/openness, NOT by this
score. Use this script to judge the quality of the fuzzy text-matching formula itself; use
`eval_scholarship_ranking_pipeline.py` (same dataset) to judge what the product actually returns.

Dataset: tests/eval/data/scholarship_matching_eval_set.json -- 30 profiles x 36 scholarships (10
universities x 10 majors controlled vocabulary, generated by the scholarship dataset generator).
`relevant_scholarship_ids` ground truth = scholarships specifically targeted at the profile's major
(target_majors is that exact major, not the "all" wildcard) -- defined structurally, independent of
the fuzzy formula under test.

Usage:
    python tests/eval/eval_scholarship_matching.py
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from app.domains.finance.agents.finance.scholarships.tools.matching import (
    _score_profile_match,
)

DATASET_PATH = Path(__file__).parent / "data" / "scholarship_matching_eval_set.json"
REPORT_DIR = Path(__file__).parent / "reports"
K_VALUES = (1, 3, 5)


def rank_for_profile(profile: dict, scholarships: dict, relevant_ids: set[str]) -> list[dict]:
    scored = []
    for sid, scholarship in scholarships.items():
        score, matched_terms = _score_profile_match(profile, scholarship)
        scored.append(
            {
                "scholarship_id": sid,
                "scholarship_name": scholarship["name"],
                "score": score,
                "matched_terms": matched_terms,
                "actually_relevant": sid in relevant_ids,
            }
        )
    scored.sort(key=lambda r: r["score"], reverse=True)
    return scored


def precision_recall_f1_at_k(ranked: list[dict], relevant_ids: set[str], k: int) -> tuple[float, float, float]:
    top_k = ranked[:k]
    hits = sum(1 for r in top_k if r["actually_relevant"])
    precision = hits / k
    recall = hits / len(relevant_ids) if relevant_ids else 0.0
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0
    return precision, recall, f1


def reciprocal_rank(ranked: list[dict]) -> float:
    for i, r in enumerate(ranked, start=1):
        if r["actually_relevant"]:
            return 1.0 / i
    return 0.0


def run() -> None:
    dataset = json.loads(DATASET_PATH.read_text(encoding="utf-8"))
    profiles = dataset["profiles"]
    scholarships = {s["id"]: s for s in dataset["scholarships"]}
    relevant_ids_map = dataset["relevant_scholarship_ids"]

    per_profile_results = []
    metrics_at_k = {k: {"precision": [], "recall": [], "f1": []} for k in K_VALUES}
    reciprocal_ranks = []

    for profile in profiles:
        pid = profile["id"]
        relevant_ids = set(relevant_ids_map.get(pid, []))
        ranked = rank_for_profile(profile, scholarships, relevant_ids)

        rr = reciprocal_rank(ranked)
        reciprocal_ranks.append(rr)

        per_k = {}
        for k in K_VALUES:
            p, r, f1 = precision_recall_f1_at_k(ranked, relevant_ids, k)
            metrics_at_k[k]["precision"].append(p)
            metrics_at_k[k]["recall"].append(r)
            metrics_at_k[k]["f1"].append(f1)
            per_k[k] = {"precision": p, "recall": r, "f1": f1}

        per_profile_results.append(
            {
                "profile_id": pid,
                "profile_label": profile["label"],
                "relevant_ids": sorted(relevant_ids),
                "ranked": ranked,
                "reciprocal_rank": rr,
                "metrics_at_k": per_k,
            }
        )

    def avg(xs: list[float]) -> float:
        return sum(xs) / len(xs) if xs else 0.0

    mrr = avg(reciprocal_ranks)
    top1_accuracy = avg([1.0 if r["ranked"][0]["actually_relevant"] else 0.0 for r in per_profile_results])

    print("=== Kết quả đánh giá gợi ý học bổng — chất lượng xếp hạng (tự động, tái lập được) ===")
    print("Thuật toán: weighted Jaccard(0.5) + Bigram(0.3) + SequenceMatcher(0.2) "
          "— công thức thật đang chạy trong sản phẩm")
    print(f"Số hồ sơ: {len(profiles)}, số học bổng: {len(scholarships)}")
    print(f"\nTop-1 accuracy (kết quả gợi ý #1 có đúng không): {top1_accuracy * 100:.1f}%")
    print(f"MRR (Mean Reciprocal Rank): {mrr:.3f}")
    print(f"\n{'K':<6}{'Precision@K':<14}{'Recall@K':<12}{'F1@K':<10}")
    for k in K_VALUES:
        p = avg(metrics_at_k[k]["precision"])
        r = avg(metrics_at_k[k]["recall"])
        f1 = avg(metrics_at_k[k]["f1"])
        print(f"{k:<6}{p * 100:<13.1f}%{r * 100:<11.1f}%{f1 * 100:<9.1f}%")

    print("\nChi tiết theo từng hồ sơ (Top-3 gợi ý):")
    for r in per_profile_results:
        top3 = r["ranked"][:3]
        marks = "".join("✓" if t["actually_relevant"] else "✗" for t in top3)
        print(f"  [{r['profile_label']:<12}] RR={r['reciprocal_rank']:.2f}  top-3={marks}  "
              f"-> {', '.join(t['scholarship_name'] for t in top3)}")

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "algorithm": "weighted Jaccard(0.5) + Bigram(0.3) + SequenceMatcher(0.2) [production formula]",
        "methodology_note": (
            "Ranking-based eval (Precision@K/Recall@K/F1@K/MRR), not a hard score "
            "threshold — matches how match_scholarships_for_profile is actually used "
            "(ranked top-N list, no hard cutoff)."
        ),
        "num_profiles": len(profiles),
        "num_scholarships": len(scholarships),
        "top1_accuracy": top1_accuracy,
        "mrr": mrr,
        "metrics_at_k": {
            k: {
                "precision": avg(metrics_at_k[k]["precision"]),
                "recall": avg(metrics_at_k[k]["recall"]),
                "f1": avg(metrics_at_k[k]["f1"]),
            }
            for k in K_VALUES
        },
        "per_profile": per_profile_results,
    }
    out_path = REPORT_DIR / f"scholarship_matching_eval_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    out_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nBáo cáo chi tiết đã lưu: {out_path}")


if __name__ == "__main__":
    run()
